def _swatch(color: tuple[int, int, int], seed: int, size: int = 500) -> bytes:
    """Distinct placeholder art per product.

    Deliberately different *shapes*, not just different colours: perceptual hashing
    keys on structure, so recolouring one motif would leave every demo product a
    near-match of every other and make reverse image search look broken.
    """
    from PIL import Image as PILImage, ImageDraw

    img = PILImage.new("RGB", (size, size), (245, 246, 248))
    d = ImageDraw.Draw(img)
    m = 60

    if seed == 0:        # earbuds - two discs, lower half
        d.ellipse([m, size // 2 - 40, size // 2 - 20, size - m], fill=color)
        d.ellipse([size // 2 + 20, size // 2 - 40, size - m, size - m], fill=color)
        d.rectangle([m + 30, m, m + 70, size // 2], fill=(30, 30, 36))
    elif seed == 2:      # hub - wide bar with ports along the top
        d.rounded_rectangle([m, size // 2 - 70, size - m, size // 2 + 70],
                            radius=26, fill=color)
        for i in range(5):
            x = m + 30 + i * 70
            d.rectangle([x, size // 2 - 46, x + 40, size // 2 - 6], fill=(240, 240, 245))
    else:                # drill - circle plus a vertical grip
        d.ellipse([m, m, size - m, size - m], fill=color)
        d.rectangle([size // 2 - 34, size // 2, size // 2 + 34, size - 20],
                    fill=(35, 35, 40))
        d.ellipse([size // 2 - 60, size // 2 - 60, size // 2 + 60, size // 2 + 60],
                  fill=(250, 250, 250))

    buf = io.BytesIO()
    img.save(buf, "PNG")
    return buf.getvalue()


IMAGES = {
    "earbuds": _swatch((36, 92, 196), 0),
    "hub": _swatch((28, 150, 120), 2),
    "drill": _swatch((208, 118, 26), 4),
}


class _LocalImageFetcher:
    """Serves the generated bytes instead of hitting the network."""

    def download(self, url: str, referer: str | None = None) -> bytes:
        for key, data in IMAGES.items():
            if key in url:
                return data
        raise RuntimeError(f"no demo image for {url}")

    def close(self) -> None:
        pass


