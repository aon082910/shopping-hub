def seed_demo() -> int:
    """Ingest the demo listings. Returns the number processed."""
    init_db()
    with session_scope() as session:
        ctx = IngestContext(session)
        ctx.images._fetcher = _LocalImageFetcher()
        try:
            for raw in LISTINGS:
                offer = ingest_offer(ctx, raw)
                log.info(
                    "  %-12s -> $%s (MOQ %s) product #%s",
                    raw.site_key, offer.price_usd, offer.moq, offer.canonical_id,
                )
        finally:
            ctx.close()
    return len(LISTINGS)
